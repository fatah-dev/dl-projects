import tensorflow as tf
from tensorflow import keras
import numpy as np
import matplotlib.pyplot as plt

x = np . arange(-80,81 , 0.5 )
y = x ** 2 + 5 *x + 3

from sklearn.model_selection import train_test_split

x_train , x_test , y_train , y_test = train_test_split(x,y , test_size=0.2)

x_train.shape , x_test.shape

model_2=keras.Sequential()
model_2.add(keras.layers.Dense(units=256 , activation='relu', input_shape=[1]))
model_2.add(keras.layers.Dense(units=256 , activation='relu'))
model_2.add(keras.layers.Dense(units=256 , activation='relu'))
model_2.add(keras.layers.Dense(units=256 , activation='relu'))
model_2.add(keras.layers.Dense(units=1 ))

optizimer = keras.optimizers.RMSprop(learning_rate = 0.001)
loss=keras.losses.MeanSquaredError()
metric=tf.metrics.RootMeanSquaredError()
model_2.compile(optimizer=optizimer,loss=loss , metrics=[metric])

from sklearn.utils.validation import validate_data
early_stop=keras.callbacks.EarlyStopping(monitor='val_loss' , patience=50 , restore_best_weights=True )

hist=model_2.fit(x_train,y_train , epochs=100 , batch_size=128 , callbacks=[early_stop], validation_data=(x_test,y_test))

plt.plot(hist.history['val_loss'],color="red")
plt.plot(hist.history['loss'],color="blue")
plt.show()