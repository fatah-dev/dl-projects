import tensorflow as tf
from tensorflow import keras

"""data definition

"""

# y=3*x-5
x=tf.constant([-1,-2,0,1,2,3,7])
x=tf.cast(x,dtype=tf.float32)

y=x*3-5

x.numpy()

y.numpy()

"""model definition"""

model=keras.Sequential([
    keras.layers.Dense(units=1,input_shape=[1])
])

#(y - y_pred)^2
model.compile(optimizer='sgd',loss='mean_squared_error')

model.summary(
)

model.fit(x,y,batch_size=1,epochs=500)

"""test"""

x_test=tf.constant([-4,11,20],dtype=float)
y_test= x_test *3 - 5

x_test.numpy()

y_test.numpy()

y_pred=model.predict(x_test)

y_pred

import matplotlib.pyplot as plt
plt.scatter(x_test.numpy(), y_test.numpy(),color='red' , linewidths=4)
plt.scatter(x_test.numpy(), y_pred,color='blue')
plt.show()

